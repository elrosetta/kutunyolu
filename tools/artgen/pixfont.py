SPACE_ADV = 3


def build(out_dir):
    chars = sorted(G.keys(), key=ord)
    cols = 16
    cw, ch = 8, LINE_H
    rows = (len(chars) + cols - 1) // cols
    W = 128
    H = 1
    while H < rows * ch:
        H *= 2
    img = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    px = img.load()
    lines = []
    for i, c in enumerate(chars):
        top, rs = G[c]
        w = max(len(r) for r in rs)
        h = len(rs)
        x0 = (i % cols) * cw
        y0 = (i // cols) * ch
        for y, r in enumerate(rs):
            for x, v in enumerate(r):
                if v == '#':
                    px[x0 + x, y0 + y] = (255, 255, 255, 255)
        lines.append('char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=%d xadvance=%d page=0 chnl=15'
                     % (ord(c), x0, y0, w, h, top, w + 1))
    lines.append('char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15' % SPACE_ADV)
    lines.append('char id=160 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15' % SPACE_ADV)
    os.makedirs(out_dir, exist_ok=True)
    img.save(os.path.join(out_dir, 'pixel.png'))
    head = [
        'info face="KutPixel" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1 outline=0' % LINE_H,
        'common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4' % (LINE_H, BASE, W, H),
        'page id=0 file="pixel.png"',
        'chars count=%d' % (len(lines)),
    ]
    with open(os.path.join(out_dir, 'pixel.fnt'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(head + lines) + '\n')
    return img


def preview(path, text):
    """Önizleme: metni 3x büyütülmüş PNG olarak yaz."""
    w = sum((max(len(r) for r in G[c][1]) + 1) if c in G else SPACE_ADV for c in text) + 4
    img = Image.new('RGBA', (w, LINE_H + 4), (20, 16, 30, 255))
    px = img.load()
    x = 2
    for c in text:
        if c not in G:
            x += SPACE_ADV
            continue
        top, rs = G[c]
        for y, r in enumerate(rs):
            for xx, v in enumerate(r):
                if v == '#':
                    px[x + xx, 2 + top + y] = (240, 232, 214, 255)
        x += max(len(r) for r in rs) + 1
    img = img.resize((img.width * 3, img.height * 3), Image.NEAREST)
    img.save(path)


